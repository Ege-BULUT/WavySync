// Latest releases, so the version shown never goes stale. The static text is the fallback.
function latest(repo, relSel, dateSel) {
  if (!document.querySelector(relSel)) return;
  fetch("https://api.github.com/repos/" + repo + "/releases/latest").then(r => r.ok ? r.json() : null).then(j => {
    if (!j || !j.tag_name) return;
    document.querySelectorAll(relSel).forEach(a => { a.textContent = j.tag_name; a.href = j.html_url; });
    if (dateSel) document.querySelectorAll(dateSel).forEach(e => { e.textContent = (j.published_at || "").slice(0, 10); });
  }).catch(() => {});
}
